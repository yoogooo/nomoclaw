CREATE TABLE IF NOT EXISTS llm_provider_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    provider_id VARCHAR(64) NOT NULL DEFAULT '',
    provider_name VARCHAR(128) NOT NULL DEFAULT '',
    protocol VARCHAR(64) NOT NULL DEFAULT '',
    base_url VARCHAR(512) NOT NULL DEFAULT '',
    api_key_ciphertext TEXT NOT NULL,
    default_model VARCHAR(128) NOT NULL DEFAULT '',
    local TINYINT(1) NOT NULL DEFAULT 0,
    require_api_key TINYINT(1) NOT NULL DEFAULT 1,
    freeze_url TINYINT(1) NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    ext_config CLOB NULL,
    created_time TIMESTAMP(3) NOT NULL,
    updated_time TIMESTAMP(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (provider_id),
    INDEX idx_llm_provider_config_status (status)
);

