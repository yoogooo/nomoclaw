    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    provider_id VARCHAR(64) NOT NULL DEFAULT '',
    model_id VARCHAR(128) NOT NULL DEFAULT '',
    model_name VARCHAR(255) NOT NULL DEFAULT '',
    capabilities_json CLOB NOT NULL,
    reasoning TINYINT(1) NOT NULL DEFAULT 0,
    context_window INT NOT NULL DEFAULT 0,
    max_input_tokens INT NOT NULL DEFAULT 0,
    max_output_tokens INT NOT NULL DEFAULT 0,
    upload_policy_json CLOB NULL,
    sort_index INT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_time TIMESTAMP(3) NOT NULL,
    updated_time TIMESTAMP(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (provider_id, model_id),
    INDEX idx_llm_provider_model_provider (provider_id, status, sort_index)
);
