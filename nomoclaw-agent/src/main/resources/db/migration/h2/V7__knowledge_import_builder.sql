UPDATE knowledge_document_version v
SET parser_mode = 'STRUCTURED',
    chunk_size_tokens = (SELECT b.chunk_size_tokens
                         FROM knowledge_document d
                         JOIN knowledge_base b ON b.knowledge_base_uid = d.knowledge_base_uid
                         WHERE d.document_uid = v.document_uid),
    chunk_overlap_tokens = (SELECT b.chunk_overlap_tokens
                            FROM knowledge_document d
                            JOIN knowledge_base b ON b.knowledge_base_uid = d.knowledge_base_uid
                            WHERE d.document_uid = v.document_uid),
    embedding_provider_id = (SELECT b.embedding_provider_id
                             FROM knowledge_document d
                             JOIN knowledge_base b ON b.knowledge_base_uid = d.knowledge_base_uid
                             WHERE d.document_uid = v.document_uid),
    embedding_model_id = (SELECT b.embedding_model_id
                          FROM knowledge_document d
                          JOIN knowledge_base b ON b.knowledge_base_uid = d.knowledge_base_uid
                          WHERE d.document_uid = v.document_uid),
    embedding_dimension = (SELECT b.embedding_dimension
                           FROM knowledge_document d
                           JOIN knowledge_base b ON b.knowledge_base_uid = d.knowledge_base_uid
                           WHERE d.document_uid = v.document_uid)
WHERE v.embedding_provider_id = '' OR v.embedding_dimension = 0;

CREATE TABLE IF NOT EXISTS knowledge_embedding_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cache_key VARCHAR(64) NOT NULL UNIQUE,
    model_fingerprint VARCHAR(512) NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    dimension INT NOT NULL,
    vector_blob BLOB NOT NULL,
    vector_bytes INT NOT NULL,
    hit_count BIGINT DEFAULT 0 NOT NULL,
    created_time TIMESTAMP(3) NOT NULL,
    last_access_time TIMESTAMP(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_knowledge_embedding_cache_cleanup
    ON knowledge_embedding_cache(last_access_time, id);
CREATE INDEX IF NOT EXISTS idx_knowledge_embedding_cache_content
    ON knowledge_embedding_cache(content_hash);
