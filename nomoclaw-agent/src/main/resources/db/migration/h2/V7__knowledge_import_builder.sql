CREATE TABLE IF NOT EXISTS knowledge_import_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_uid VARCHAR(64) NOT NULL UNIQUE,
    knowledge_base_uid VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    parser_mode VARCHAR(32) DEFAULT 'STRUCTURED' NOT NULL,
    chunk_size_tokens INT DEFAULT 500 NOT NULL,
    chunk_overlap_tokens INT DEFAULT 80 NOT NULL,
    embedding_provider_id VARCHAR(64) DEFAULT '' NOT NULL,
    embedding_model_id VARCHAR(128) DEFAULT '' NOT NULL,
    embedding_dimension INT DEFAULT 0 NOT NULL,
    embedding_model_fingerprint VARCHAR(512) DEFAULT '' NOT NULL,
    config_hash VARCHAR(64) DEFAULT '' NOT NULL,
    created_time TIMESTAMP(3) NOT NULL,
    updated_time TIMESTAMP(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_knowledge_import_batch_base
    ON knowledge_import_batch(knowledge_base_uid, status, id);

CREATE TABLE IF NOT EXISTS knowledge_import_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_uid VARCHAR(64) NOT NULL UNIQUE,
    batch_uid VARCHAR(64) NOT NULL,
    document_uid VARCHAR(64),
    document_version_uid VARCHAR(64),
    original_file_name VARCHAR(255) NOT NULL,
    mode VARCHAR(16) DEFAULT 'UPLOAD' NOT NULL,
    outcome VARCHAR(16) NOT NULL,
    status VARCHAR(32) NOT NULL,
    error_code VARCHAR(64) DEFAULT '' NOT NULL,
    error_message CLOB,
    created_time TIMESTAMP(3) NOT NULL,
    updated_time TIMESTAMP(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_knowledge_import_item_batch ON knowledge_import_item(batch_uid, id);
CREATE INDEX IF NOT EXISTS idx_knowledge_import_item_version ON knowledge_import_item(document_version_uid);

